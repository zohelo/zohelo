// Turns tokens.json (W3C DTCG) into dist/tokens.css (CSS variables, light and dark),
// dist/theme.css (Tailwind 4 @theme) and src/generated/tokens.ts (typed values), and copies
// src/fonts.css to dist/fonts.css.
// Run from anywhere: paths resolve from this file.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

type Token = { $value: unknown; $type?: string; $extensions?: { dark?: unknown } };
type Flat = { group: string; name: string; value: string; dark?: string; raw: unknown };

const isToken = (node: unknown): node is Token =>
  typeof node === 'object' && node !== null && '$value' in node;

function cssValue(value: unknown): string {
  if (Array.isArray(value)) {
    return value.map((f) => (/^[a-z-]+$/.test(String(f)) ? String(f) : `'${f}'`)).join(', ');
  }
  return String(value);
}

export function flatten(tokens: Record<string, unknown>): Flat[] {
  const out: Flat[] = [];
  for (const [group, tree] of Object.entries(tokens)) {
    const walk = (node: unknown, path: string[]) => {
      if (isToken(node)) {
        const dark = node.$extensions?.dark;
        out.push({
          group,
          name: path.join('-'),
          value: cssValue(node.$value),
          dark: dark === undefined ? undefined : cssValue(dark),
          raw: node.$value,
        });
        return;
      }
      for (const [key, child] of Object.entries(node as Record<string, unknown>)) {
        if (!key.startsWith('$')) walk(child, [...path, key]);
      }
    };
    walk(tree, []);
  }
  return out;
}

const varName = (t: Flat) => `--z-${t.group}-${t.name}`;
const camel = (s: string) => s.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());

export function tokensCss(flat: Flat[]): string {
  const light = flat.map((t) => `  ${varName(t)}: ${t.value};`).join('\n');
  const darkLines = flat.filter((t) => t.dark !== undefined);
  const dark = (indent: string) => darkLines.map((t) => `${indent}${varName(t)}: ${t.dark};`).join('\n');
  return [
    '/* Generated by scripts/build-tokens.ts from tokens.json. Do not edit. */',
    `:root {\n${light}\n}`,
    `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme=light]) {\n${dark('    ')}\n  }\n}`,
    `:root[data-theme=dark] {\n${dark('  ')}\n}`,
    '',
  ].join('\n\n');
}

export function themeCss(flat: Flat[]): string {
  const prefix: Record<string, string> = { color: 'color', font: 'font', radius: 'radius' };
  const lines = flat
    .filter((t) => t.group in prefix)
    .map((t) => `  --${prefix[t.group]}-${t.name}: var(${varName(t)});`);
  return [
    '/* Generated by scripts/build-tokens.ts from tokens.json. Do not edit. */',
    `@theme {\n${lines.join('\n')}\n}`,
    '',
  ].join('\n\n');
}

export function tokensTs(flat: Flat[]): string {
  const colors = flat.filter((t) => t.group === 'color');
  const light = Object.fromEntries(colors.map((t) => [t.name, t.value]));
  const dark = Object.fromEntries(colors.map((t) => [t.name, t.dark ?? t.value]));
  const obj: Record<string, unknown> = { light, dark };
  for (const t of flat) {
    if (t.group === 'color') continue;
    const group = (obj[camel(t.group)] ??= {}) as Record<string, unknown>;
    group[t.name] = t.dark === undefined ? t.raw : { light: t.raw, dark: t.dark };
  }
  return [
    '// Generated by scripts/build-tokens.ts from tokens.json. Do not edit.',
    `export const tokens = ${JSON.stringify(obj, null, 2)} as const;`,
    '',
    'export type Tokens = typeof tokens;',
    '',
  ].join('\n');
}

if (import.meta.main) {
  const flat = flatten(JSON.parse(readFileSync(join(root, 'tokens.json'), 'utf8')));
  mkdirSync(join(root, 'dist'), { recursive: true });
  mkdirSync(join(root, 'src/generated'), { recursive: true });
  writeFileSync(join(root, 'dist/tokens.css'), tokensCss(flat));
  writeFileSync(join(root, 'dist/theme.css'), themeCss(flat));
  writeFileSync(join(root, 'src/generated/tokens.ts'), tokensTs(flat));
  copyFileSync(join(root, 'src/fonts.css'), join(root, 'dist/fonts.css'));
  console.log(`tokens: ${flat.length} written to dist/tokens.css, dist/theme.css, src/generated/tokens.ts`);
}
